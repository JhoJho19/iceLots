using System;
using System.Collections.Generic;
using System.Linq;
using IceP.Domain.Configuration;

namespace IceP.Domain.SlotEngine
{
    public sealed class ScatterEvaluation
    {
        public int ScatterCount { get; }
        public int AwardedFreeSpins { get; }
        public bool BonusTriggered => AwardedFreeSpins > 0;
        internal ScatterEvaluation(int scatterCount, int awardedFreeSpins)
        {
            ScatterCount = scatterCount;
            AwardedFreeSpins = awardedFreeSpins;
        }
    }

    public sealed class ScatterEvaluator
    {
        private readonly SymbolId scatterId;
        private readonly IReadOnlyDictionary<int, int> awards;
        private readonly bool retriggerEnabled;

        public ScatterEvaluator(SlotRuntimeConfig config)
        {
            if (config == null) throw new ArgumentNullException(nameof(config));
            ConfigValidator.ValidateAndThrow(config);
            scatterId = config.ScatterId;
            awards = config.Scatter.Awards.ToDictionary(a => a.ScatterCount, a => a.FreeSpins);
            retriggerEnabled = config.Scatter.RetriggerEnabled;
        }

        public ScatterEvaluation Evaluate(SlotGrid grid, bool isFreeSpin = false)
        {
            if (grid == null) throw new ArgumentNullException(nameof(grid));
            var count = 0;
            for (var reel = 0; reel < SlotGrid.ReelCount; reel++)
                for (var row = 0; row < SlotGrid.RowCount; row++)
                    if (grid[reel, row] == scatterId) count++;
            // Exact configured rewards. Counts above five cannot be generated by v1 strips.
            var reward = (!isFreeSpin || retriggerEnabled) && awards.TryGetValue(count, out var spins) ? spins : 0;
            return new ScatterEvaluation(count, reward);
        }
    }
}
